"""Generate backend route metadata and the TypeScript SDK from the canonical API."""
import argparse
import json
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
spec = yaml.safe_load((ROOT / 'contracts/openapi.yaml').read_text(encoding='utf-8'))
routes = []
for path, methods in spec['paths'].items():
    for method, op in methods.items():
        params = op.get('parameters', [])
        routes.append(dict(method=method.upper(), path=path, operationId=op['operationId'],
            permission=op['x-required-permission'], tag=op['tags'][0],
            request=op.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema', {}).get('$ref', '').split('/')[-1],
            response=next(v for k,v in op['responses'].items() if k.startswith('2'))['content']['application/json']['schema']['$ref'].split('/')[-1],
            status=int(next(k for k in op['responses'] if k.startswith('2'))),
            public=op.get('security') == [], webhook=op['tags'][0]=='Webhooks',
            idempotent=any(p['name']=='Idempotency-Key' for p in params),
            etag=any(p['name']=='If-Match' for p in params)))

def ts_type(s):
    if 'anyOf' in s: return ' | '.join(ts_type(choice) for choice in s['anyOf'])
    if '$ref' in s: return s['$ref'].split('/')[-1]
    if 'enum' in s: return ' | '.join(json.dumps(x) for x in s['enum'])
    typ=s.get('type')
    if isinstance(typ,list): return ' | '.join(ts_type(dict(s,type=t)) for t in typ)
    if typ=='array': return f'Array<{ts_type(s["items"])}>'
    if typ=='object':
        if not s.get('properties'): return 'Record<string, unknown>'
        req=s.get('required',[])
        return '{ '+ '; '.join(f'{k}{"" if k in req else "?"}: {ts_type(v)}' for k,v in s['properties'].items())+' }'
    return {'integer':'number','number':'number','boolean':'boolean','null':'null','string':'string'}.get(typ,'unknown')

types='// Generated by scripts/generate_contracts.py; edit contracts/generate_openapi.py.\n'
types+='\n'.join('export type '+name+' = '+ts_type(s)+';' for name,s in spec['components']['schemas'].items())
types+='\nexport const operations = '+json.dumps(routes,ensure_ascii=False,indent=2)+' as const;\n'
types+=r'''
import {randomId} from './browser-crypto';
import {validateRequest} from './validation';
export class ApiError extends Error {
  constructor(public problem: Problem, public status: number) { super(problem.detail || problem.title); }
}
export async function request<T>(path: string, options: RequestInit = {}): Promise<T> {
  const method=(options.method||'GET').toUpperCase(),pathname=path.split('?')[0];
  const operation=operations.find(op=>op.method===method&&new RegExp('^'+op.path.replace(/\{[^}]+\}/g,'[^/]+')+'$').test(pathname));
  if(operation?.request)validateRequest(operation.request,options.body?JSON.parse(String(options.body)):{});
  const headers = new Headers(options.headers);
  if (options.body) headers.set('Content-Type', 'application/json');
  if (options.method && !['GET', 'HEAD'].includes(options.method)) {
    const session = await fetch('/api/session', {cache:'no-store'}).then(r => r.json());
    if (session.csrfToken) headers.set('X-CSRF-Token', session.csrfToken);
    headers.set('Idempotency-Key', headers.get('Idempotency-Key') || randomId());
  }
  const response = await fetch('/api/bff'+path, {...options, headers, cache:'no-store'});
  if (!response.ok) throw new ApiError(await response.json(),response.status);
  return response.json() as Promise<T>;
}
'''
outputs={
    ROOT/'apps/web/src/lib/api.schemas.generated.json':json.dumps(spec['components']['schemas'],ensure_ascii=False,separators=(',',':'))+'\n',
    ROOT/'backend/src/main/resources/contracts/routes.json':json.dumps(routes,ensure_ascii=False,indent=2)+'\n',
    ROOT/'backend/src/main/resources/contracts/schemas.json':json.dumps(spec['components']['schemas'],ensure_ascii=False,indent=2)+'\n',
    ROOT/'apps/web/src/lib/api.generated.ts':types,
}
parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
for path,content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8')!=content: raise SystemExit('Contrato desatualizado: '+str(path.relative_to(ROOT)))
    else:
        path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content,encoding='utf-8')
print(f'{len(routes)} operações e {len(spec["components"]["schemas"])} schemas sincronizados.')
